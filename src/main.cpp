// ==============================================================================
// 1. ПІДКЛЮЧЕННЯ БІБЛІОТЕК (Навчаємо ESP32 нових навичок)
// ==============================================================================
#include <Arduino.h>            // Базова бібліотека для роботи всіх функцій Arduino
#include <WiFi.h>               // Бібліотека для підключення ESP32 до домашнього роутера
#include <ESPAsyncWebServer.h>  // Сучасний асинхронний сервер (обробляє запити у фоні)
#include <SPIFFS.h>             // Бібліотека для роботи з вбудованою флеш-пам'яттю (папка data)
#include <DHT.h>                // Бібліотека для спілкування з датчиком температури та вологості

// ==============================================================================
// 2. ГЛОБАЛЬНІ ЗМІННІ (Налаштування нашої мережі та обладнання)
// ==============================================================================
// const char* - це покажчик на незмінний текст (економить оперативну пам'ять)
const char* ssid = "Lana";           // Назва твоєї Wi-Fi мережі
const char* password = "0506153641"; // Пароль від твоєї Wi-Fi мережі

// Створюємо об'єкт 'dht'. Кажемо йому: "Ти підключений до 13 піна, і твоя модель DHT11"
DHT dht(13, DHT11);

// Створюємо об'єкт сервера і кажемо йому "слухати" 80-й порт (світовий стандарт для веб-сайтів)
AsyncWebServer server(80);

// ==============================================================================
// 3. ФУНКЦІЯ-ОБРОБНИК (Template Processor) - Магія динамічних даних
// ==============================================================================
/* Як це працює: 
   Коли сервер бере файл index.html зі SPIFFS, щоб відправити його браузеру,
   він спочатку сканує весь текст. Якщо він бачить слово, затиснуте між відсотками 
   (наприклад, %TEMPERATURE%), він викликає цю функцію і передає їй слово "TEMPERATURE".
   Те, що ця функція поверне (return), сервер вставить у HTML замість %TEMPERATURE%.
*/
String processor(const String& var) {
  // Перевіряємо, чи запитав сервер у нас температуру
  if (var == "TEMPERATURE") {
    float t = dht.readTemperature(); // Зчитуємо температуру з датчика
    
    // isnan (Is Not A Number). Перевіряємо, чи не заглючив датчик
    if (isnan(t)) return "Error"; 
    
    // Перетворюємо дробове число (float) у текст (String). 
    // Цифра '1' означає: "залиши тільки 1 знак після коми" (наприклад, 25.4 замість 25.4000)
    return String(t, 1); 
  }
  // Перевіряємо, чи запитав сервер у нас вологість
  else if (var == "HUMIDITY") {
    float h = dht.readHumidity(); // Зчитуємо вологість
    
    if (isnan(h)) return "Error"; // Захист від помилок датчика
    
    return String(h, 1); // Перетворюємо на текст з 1 знаком після коми
  }
  
  // Якщо сервер знайшов маркер %...%, але ми не знаємо такого слова, 
  // просто повертаємо порожнє місце, щоб не зламати код сторінки.
  return String(); 
}

// ==============================================================================
// 4. ФУНКЦІЯ SETUP (Виконується лише 1 раз при запуску ESP32)
// ==============================================================================
void setup() {
  Serial.begin(115200); // Відкриваємо канал зв'язку з комп'ютером (Монітор порту)
  dht.begin();          // "Будимо" датчик DHT11, щоб він почав робити заміри

  // --- Крок А: Запуск файлової системи SPIFFS ---
  // true означає: "Якщо файлова система пошкоджена або не створена - відформатуй її"
  if (!SPIFFS.begin(true)) {
    Serial.println("Помилка монтування SPIFFS! (Перевір, чи завантажив ти файли через Upload File System Image)");
    return; // Якщо пам'ять не працює, зупиняємо подальше виконання setup()
  }

  // --- Крок Б: Підключення до Wi-Fi ---
  WiFi.begin(ssid, password);
  Serial.print("Підключення до Wi-Fi");
  
  // Поки статус Wi-Fi не дорівнює "Підключено", друкуємо крапочки кожні 0.5 секунди
  while (WiFi.status() != WL_CONNECTED) {
    delay(500);
    Serial.print(".");
  }
  
  Serial.println("\nПідключено! Введи цю IP адресу в браузері телефону:");
  Serial.println(WiFi.localIP()); // Виводимо адресу, яку нам видав роутер (напр., 192.168.1.50)

  // --- Крок В: НАЛАШТУВАННЯ МАРШРУТІВ (Routing) АСИНХРОННОГО СЕРВЕРА ---
  
  // 1. Головна сторінка. 
  // Коли браузер стукає в корінь ("/") методом HTTP_GET, виконується цей код:
  server.on("/", HTTP_GET,[](AsyncWebServerRequest *request){
    // Відправляємо файл з SPIFFS. 
    // Параметри: (Джерело, "Шлях", MIME-тип (String() - автовизначення), Чи_завантажувати_як_файл (false), функція-процесор)
    // САМЕ ТУТ ми передаємо нашу функцію processor, щоб сервер підставив температуру в HTML!
    request->send(SPIFFS, "/index.html", String(), false, processor);
  });

  // 2. Файл стилів.
  // Коли браузер знайде в HTML тег <link href="/style.css">, він попросить цей файл.
  server.on("/style.css", HTTP_GET,[](AsyncWebServerRequest *request){
    // Тут функція processor НЕ ПОТРІБНА, бо стилі статичні і не змінюються.
    request->send(SPIFFS, "/style.css", "text/css");
  });

  // 3. Зображення (Картинки для температури)
  server.on("/temp.png", HTTP_GET,[](AsyncWebServerRequest *request){
    // Віддаємо картинку, чітко вказавши браузеру MIME-тип "image/png"
    request->send(SPIFFS, "/temp.png", "image/png");
  });

  // 4. Зображення (Картинки для вологості)
  // Без цього маршруту браузер не зможе показати картинку, навіть якщо вона є у флеш-пам'яті.
  // server.on("/hum.png", HTTP_GET,[](AsyncWebServerRequest *request){
  //   request->send(SPIFFS, "/hum.png", "image/png");
  // });

  // --- Крок Г: Фінальний запуск ---
  server.begin(); // Вмикаємо сервер. Відтепер він працює сам по собі!
  Serial.println("Асинхронний сервер запущено!");
}

// ==============================================================================
